func GetTaskByIdHandler(pool *pgxpool.Pool) gin.HandlerFunc {
	return func(c *gin.Context) {
		taskId := c.Param("id")

		// convert an int or number enclosed in "" to an integer (without the string), e.g. "2" to 2
		id, err := strconv.Atoi(taskId)

		if err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
			return
		}

		user, exists := c.Get("user_id")

		if !exists {
			c.JSON(http.StatusUnauthorized, gin.H{"error": "User ID unavailable in context!"})
			return
		}

		userId := user.(string)

		task, err := repo.GetTaskById(pool, id, userId)

		if err != nil {
			if err == pgx.ErrNoRows {
				c.JSON(http.StatusNotFound, gin.H{"error": "Task not found!"})
				return
			}

			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
			return
		}

		c.JSON(http.StatusOK, task)
	}
}

func UpdateTaskHandler(pool *pgxpool.Pool) gin.HandlerFunc {
	return func(c *gin.Context) {
		taskId := c.Param("id")

		id, err := strconv.Atoi(taskId)

		if err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid ID provided!"})
			return
		}

		user, exists := c.Get("user_id")

		if !exists {
			c.JSON(http.StatusUnauthorized, gin.H{"error": "User ID unavailable in context!"})
			return
		}

		userId := user.(string)

		var payload UpdateTaskRequest

		if err := c.ShouldBindJSON(&payload); err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
			return
		}

		task, err := repo.UpdateTask(pool, id, payload.Title, payload.Description, payload.Completed, userId)

		if err != nil {
			if err == pgx.ErrNoRows {
				c.JSON(http.StatusNotFound, gin.H{"error": "Task not found!"})
				return
			}

			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		}

		c.JSON(http.StatusOK, task)
	}
}

func DeleteTaskHandler(pool *pgxpool.Pool) gin.HandlerFunc {
	return func(c *gin.Context) {
		taskId := c.Param("id")

		id, err := strconv.Atoi(taskId)

		if err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid ID provided!"})
			return
		}

		user, exists := c.Get("user_id")

		if !exists {
			c.JSON(http.StatusUnauthorized, gin.H{"error": "User ID unavailable in context!"})
			return
		}

		userId := user.(string)

		err = repo.DeleteTask(pool, id, userId)

		if err != nil {
			errorMessage := "Task with id " + taskId + "not found!"
			if err.Error() == errorMessage {
				c.JSON(http.StatusNotFound, gin.H{"error": "Task not found!"})
				return
			}

			// check if there was a problem generated by the DB
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		}

		c.JSON(http.StatusNoContent, gin.H{"message": "Task deleted successfully!"})

	}
}